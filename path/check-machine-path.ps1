# ============================================================
# Windows 시스템 PATH 환경변수 확인
#
# 기능:
#   시스템 전체(Machine)에 등록된 PATH를 확인합니다.
#
# 처리 범위:
#   파일이나 폴더를 검색하지 않습니다.
#
# 실행 환경:
#   Windows PowerShell
#
# 실행 방법:
#   PowerShell에서 이 파일을 실행합니다.
#
# 출력:
#   시스템 PATH에 등록된 각 경로를 한 줄씩 표시합니다.
# ============================================================

[Environment]::GetEnvironmentVariable("Path", "Machine") -split ';'
