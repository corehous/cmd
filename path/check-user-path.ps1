# ============================================================
# Windows 사용자 PATH 환경변수 확인
#
# 기능:
#   현재 사용자(User) 계정에 등록된 PATH 환경변수를
#   가져와 각 경로를 한 줄씩 출력합니다.
#
# 처리 범위:
#   파일이나 폴더를 검색하지 않습니다.
#   현재 사용자 PATH 환경변수만 확인합니다.
#
# Machine PATH와의 차이:
#   Machine → 컴퓨터 전체에 등록된 PATH
#   User    → 현재 사용자 계정에 등록된 PATH
#
# 실행 환경:
#   Windows PowerShell
#
# 실행 방법:
#   PowerShell에서 이 파일을 실행합니다.
#
# 출력:
#   사용자 PATH에 등록된 각 경로가 한 줄씩 표시됩니다.
#
# 참고:
#   Windows PATH의 각 경로는 세미콜론(;)으로 구분됩니다.
#   -split ';'을 사용하여 각 경로를 한 줄씩 표시합니다.
# ============================================================

[Environment]::GetEnvironmentVariable("Path", "User") -split ';'
