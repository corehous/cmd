# ============================================================
# Windows PATH 환경변수 확인
#
# 기능:
#   현재 PowerShell 세션의 PATH 환경변수에 등록된
#   모든 경로를 한 줄씩 출력합니다.
#
# 처리 범위:
#   파일이나 폴더를 검색하지 않습니다.
#   현재 시스템의 PATH 환경변수만 확인합니다.
#
# 주요 용도:
#   Node.js, npm, Python, ffmpeg, Poppler 등의 프로그램이
#   PATH에 등록되어 있는지 확인할 때 사용합니다.
#
# 실행 환경:
#   Windows PowerShell
#
# 실행 방법:
#   PowerShell에서 아래 코드를 실행합니다.
#
#   $env:Path -split ';'
#
# 출력:
#   PATH에 등록된 각 경로가 한 줄씩 표시됩니다.
#
# 참고:
#   PATH의 각 경로는 Windows에서 세미콜론(;)으로 구분됩니다.
#   -split ';'을 사용하면 이를 각각의 항목으로 나누어 출력합니다.
# ============================================================

$env:Path -split ';'
